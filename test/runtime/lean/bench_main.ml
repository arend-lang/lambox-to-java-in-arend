(* The one file in this directory that is ours, not upstream's -- and it is the
   same two lines upstream's natio.ml.template generates, minus the command-line
   argument: our cases close the benchmark over its input during erasure, so the
   erased term is a closed Lean `Nat`.

   `bench.mli` (generated by lean-to-lambdabox, `#erase ... mli`) says
   `val main: Z.t`, and the realizations in `nat.ml` represent a Nat as a Zarith
   integer, so printing it with `Z.to_string` yields exactly the decimal digits
   our Java backend prints for the same program -- which is what makes the two
   backends comparable by string equality (see test/check-case.sh). *)
